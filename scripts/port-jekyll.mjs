#!/usr/bin/env node
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import matter from 'gray-matter';

const ROOT = path.resolve(new URL('.', import.meta.url).pathname, '..');
const POSTS_IN = path.join(ROOT, '_posts');
const DRAFTS_IN = path.join(ROOT, '_drafts');
const POSTS_OUT = path.join(ROOT, 'src/content/posts');
const REDIRECTS_MJS = path.join(ROOT, 'src/redirects.mjs');
const VERCEL_JSON = path.join(ROOT, 'vercel.json');

const STRIP_FIELDS = new Set([
  'layout', 'author', 'header', 'classes', 'comments', 'author_profile',
  'read_time', 'share', 'related', 'show_date', 'permalink', 'toc',
  'sidebar', 'tags',
]);

const KNOWN_FIELDS = new Set([
  'title', 'date', 'excerpt', 'categories', 'draft', 'redirectFrom',
]);

function deriveSlug(filename) {
  const base = filename.replace(/\.(md|markdown)$/, '');
  return base.replace(/^\d{4}-\d{2}-\d{2}-/, '');
}

function formatDateISO(d) {
  if (d instanceof Date && !isNaN(d)) return d.toISOString();
  return new Date(d).toISOString();
}

function yamlEscape(str) {
  if (typeof str !== 'string') return JSON.stringify(str);
  if (/[:#\n"'\\]|^[\s\-]|[\s]$/.test(str)) return JSON.stringify(str);
  return str;
}

function emitFrontmatter(data) {
  const lines = ['---'];
  lines.push(`title: ${yamlEscape(data.title)}`);
  lines.push(`date: ${formatDateISO(data.date)}`);
  lines.push(`excerpt: ${yamlEscape(data.excerpt)}`);
  if (data.categories && data.categories.length) {
    lines.push('categories:');
    for (const c of data.categories) lines.push(`  - ${yamlEscape(c)}`);
  }
  if (data.draft) lines.push('draft: true');
  if (data.redirectFrom && data.redirectFrom.length) {
    lines.push('redirectFrom:');
    for (const r of data.redirectFrom) lines.push(`  - ${yamlEscape(r)}`);
  }
  lines.push('---');
  return lines.join('\n');
}

async function portDir(dir, { isDraft }) {
  let entries = [];
  try {
    entries = await readdir(dir);
  } catch {
    return [];
  }
  const results = [];
  for (const f of entries) {
    if (!/\.(md|markdown)$/.test(f)) continue;
    const full = path.join(dir, f);
    const raw = await readFile(full, 'utf8');
    const parsed = matter(raw);
    const data = parsed.data;

    const unknownFields = Object.keys(data).filter(
      (k) => !KNOWN_FIELDS.has(k) && !STRIP_FIELDS.has(k) && k !== 'redirect_from' && k !== 'excerpt_separator'
    );

    const out = {
      title: data.title,
      date: data.date,
      excerpt: data.excerpt ?? '',
      categories: Array.isArray(data.categories) ? data.categories : (data.categories ? [data.categories] : undefined),
      draft: isDraft || data.published === false,
      redirectFrom: Array.isArray(data.redirect_from) ? data.redirect_from : (data.redirect_from ? [data.redirect_from] : undefined),
    };

    if (!out.title) {
      console.warn(`  ! ${f}: missing title — skipping`);
      continue;
    }
    if (!out.excerpt) {
      console.warn(`  ! ${f}: missing excerpt — using title as fallback`);
      out.excerpt = out.title;
    }

    let body = parsed.content;

    body = body.replace(/\{\{\s*site\.baseurl\s*\}\}([a-z0-9-]+)/g, '/$1');

    if (isDraft) {
      body = body.replace(/^#\s+[^\n]+\n+/, '');
    }

    body = body.trimStart();

    const slug = deriveSlug(f);
    const outPath = path.join(POSTS_OUT, `${slug}.md`);
    const content = `${emitFrontmatter(out)}\n${body}`;
    await writeFile(outPath, content);

    results.push({ slug, source: f, redirectFrom: out.redirectFrom ?? [], unknownFields });
  }
  return results;
}

async function main() {
  await rm(POSTS_OUT, { recursive: true, force: true });
  await mkdir(POSTS_OUT, { recursive: true });

  console.log('Porting _posts/...');
  const posts = await portDir(POSTS_IN, { isDraft: false });
  console.log(`  → ${posts.length} posts`);

  console.log('Porting _drafts/...');
  const drafts = await portDir(DRAFTS_IN, { isDraft: true });
  console.log(`  → ${drafts.length} drafts`);

  const all = [...posts, ...drafts];
  const redirectPairs = [];
  for (const entry of all) {
    for (const from of entry.redirectFrom) {
      redirectPairs.push([from, `/${entry.slug}`]);
    }
    if (entry.unknownFields.length) {
      console.warn(`  ? ${entry.source}: unknown frontmatter fields: ${entry.unknownFields.join(', ')}`);
    }
  }

  const astroRedirects = Object.fromEntries(redirectPairs);
  const astroRedirectsSource = `// Generated by scripts/port-jekyll.mjs — do not edit by hand.
export const REDIRECTS = ${JSON.stringify(astroRedirects, null, 2)};
`;
  await writeFile(REDIRECTS_MJS, astroRedirectsSource);

  const vercelRedirects = redirectPairs.map(([source, destination]) => ({
    source,
    destination,
    permanent: true,
  }));
  vercelRedirects.push({
    source: '/sitemap.xml',
    destination: '/sitemap-index.xml',
    permanent: true,
  });
  const vercelJson = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    redirects: vercelRedirects,
  };
  await writeFile(VERCEL_JSON, JSON.stringify(vercelJson, null, 2) + '\n');

  console.log(`\nGenerated ${redirectPairs.length} redirect(s) → src/redirects.mjs + vercel.json`);
  console.log(`Total posts written: ${all.length}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
